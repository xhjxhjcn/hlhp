// Emit the CSS block that provides always-valid base cursors, generated from
// the extracted frame data so the SVG payloads can't drift out of sync.
//
// A `cursor` declaration is only valid when the url() is followed by a keyword
// fallback, so every value here ends with `, auto` / `, pointer` / `, text`.
import { FRAMES, BASE } from "../src/assets/js/cursor-frames.js";

const cssEscape = (svg) => svg.replace(/"/g, "%22");

const frameValue = (key, keyword) => {
  const frame = FRAMES[BASE[key]];
  return `url("${cssEscape(frame.source)}") ${frame.x} ${frame.y}, ${keyword}`;
};

const lines = [];
lines.push("/* ------------------------------------------------------------------ */");
lines.push("/* Base paper-fold cursors.                                           */");
lines.push("/* Generated by tools/cursor-css.mjs from cursor-frames.js.            */");
lines.push("/* Each value ends in a keyword fallback, otherwise the whole          */");
lines.push("/* declaration is invalid CSS and the browser silently uses `auto`.    */");
lines.push("/* ------------------------------------------------------------------ */");
lines.push(":root {");
lines.push(`  --site-cursor-base-arrow: ${frameValue("arrow", "auto")};`);
lines.push(`  --site-cursor-base-link: ${frameValue("link", "pointer")};`);
lines.push(`  --site-cursor-base-text: ${frameValue("text", "text")};`);
lines.push(`  --site-cursor-base-grab: ${frameValue("paper", "grab")};`);
lines.push(`  --site-cursor-base-grabbing: ${frameValue("paper", "grabbing")};`);
lines.push("}");
lines.push("");
lines.push("html.site-pointer-ready {");
lines.push("  --site-cursor-arrow: var(--site-cursor-fold-frame, var(--site-cursor-base-arrow));");
lines.push("  --site-cursor-link: var(--site-cursor-fold-frame, var(--site-cursor-base-link));");
lines.push("  --site-cursor-text: var(--site-cursor-fold-frame, var(--site-cursor-base-text));");
lines.push("  --site-cursor-grab: var(--site-cursor-fold-frame, var(--site-cursor-base-grab));");
lines.push("  --site-cursor-grabbing: var(--site-cursor-fold-frame, var(--site-cursor-base-grabbing));");
lines.push("}");

process.stdout.write(lines.join("\n"));
